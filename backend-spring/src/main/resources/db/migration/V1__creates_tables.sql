CREATE TABLE user_evaluation (
             evaluation_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             user_id              BIGINT NOT NULL,
             area_id              BIGINT,
             goal_type            VARCHAR(50),
             overall_score        NUMERIC(5,2) NOT NULL,
             formation_score      NUMERIC(5,2),
             experience_score     NUMERIC(5,2),
             ability_score        NUMERIC(5,2),
             certification_score  NUMERIC(5,2),
             project_score        NUMERIC(5,2),
             language_score       NUMERIC(5,2),
             completeness_score   NUMERIC(5,2),
             goal_fit_score       NUMERIC(5,2),
             summary              TEXT,
             strengths            JSONB,
             weaknesses           JSONB,
             suggestions          JSONB,
             ai_model             VARCHAR(100) NOT NULL,
             rubric_version       VARCHAR(20)  NOT NULL,
             content_hash         VARCHAR(64)  NOT NULL,
             status               VARCHAR(20)  NOT NULL, -- PENDING, COMPLETED, FAILED
             is_current           BOOLEAN      NOT NULL DEFAULT TRUE,
             created_at           TIMESTAMP    NOT NULL DEFAULT NOW(),
             CONSTRAINT fk_user_evaluation_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                 ON DELETE CASCADE ON UPDATE CASCADE,
             CONSTRAINT fk_user_evaluation_area FOREIGN KEY (area_id) REFERENCES area(area_id)
                 ON DELETE SET NULL ON UPDATE CASCADE,
             CONSTRAINT chk_user_evaluation_scores CHECK (
                 overall_score BETWEEN 0 AND 100
                     AND (formation_score     IS NULL OR formation_score     BETWEEN 0 AND 100)
                     AND (experience_score    IS NULL OR experience_score    BETWEEN 0 AND 100)
                     AND (ability_score       IS NULL OR ability_score       BETWEEN 0 AND 100)
                     AND (certification_score IS NULL OR certification_score BETWEEN 0 AND 100)
                     AND (project_score       IS NULL OR project_score       BETWEEN 0 AND 100)
                     AND (language_score      IS NULL OR language_score      BETWEEN 0 AND 100)
                     AND (completeness_score  IS NULL OR completeness_score  BETWEEN 0 AND 100)
                     AND (goal_fit_score      IS NULL OR goal_fit_score      BETWEEN 0 AND 100)
                 )
);

CREATE UNIQUE INDEX uq_user_evaluation_one_current ON user_evaluation (user_id) WHERE is_current;
CREATE INDEX idx_user_evaluation_area_goal_score ON user_evaluation (area_id, goal_type, overall_score DESC) WHERE is_current;

