CREATE TABLE area (
                      area_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE enterprise (
                            enterprise_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE institution (
                             institution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE role (
                      role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      type VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE language (
                          language_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE ability (
                         ability_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE social_network (
                                social_network_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE course (
                        course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE users (
                       user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(150) NOT NULL,
                       email VARCHAR(150) NOT NULL UNIQUE,
                       password VARCHAR(255) NOT NULL,
                       area_id BIGINT,
                       CONSTRAINT fk_users_area FOREIGN KEY (area_id) REFERENCES area(area_id)
);

CREATE TABLE availability (
                              availability_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              start_availability DATE,
                              work_model VARCHAR(50) NOT NULL,
                              user_id BIGINT NOT NULL,
                              CONSTRAINT uq_availability_user UNIQUE (user_id),
                              CONSTRAINT fk_availability_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                                  ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE formation (
                           formation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           formation_type VARCHAR(100) NOT NULL,
                           start_date DATE NOT NULL,
                           finish_date DATE,
                           in_progress BOOLEAN DEFAULT FALSE,
                           user_id BIGINT NOT NULL,
                           course_id BIGINT NOT NULL,
                           CONSTRAINT fk_formation_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                               ON DELETE CASCADE ON UPDATE CASCADE,
                           CONSTRAINT fk_formation_course FOREIGN KEY (course_id) REFERENCES course(course_id)
                               ON DELETE RESTRICT ON UPDATE CASCADE,
                           CONSTRAINT chk_formation_dates CHECK (
                               finish_date IS NULL OR start_date <= finish_date
                               ),
                           CONSTRAINT chk_formation_in_progress CHECK (
                               NOT (in_progress = TRUE AND finish_date IS NOT NULL)
                               )
);

CREATE TABLE experience (
                            experience_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            title VARCHAR(150) NOT NULL,
                            position VARCHAR(150) NOT NULL,
                            description TEXT NOT NULL,
                            start_date DATE NOT NULL,
                            finish_date DATE,
                            work_current BOOLEAN DEFAULT FALSE,
                            user_id BIGINT NOT NULL,
                            area_id BIGINT,
                            enterprise_id BIGINT,
                            CONSTRAINT fk_experience_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                                ON DELETE CASCADE ON UPDATE CASCADE,
                            CONSTRAINT fk_experience_enterprise FOREIGN KEY (enterprise_id) REFERENCES enterprise(enterprise_id),
                            CONSTRAINT fk_experience_area FOREIGN KEY (area_id) REFERENCES area(area_id)
                                ON DELETE SET NULL ON UPDATE CASCADE,
                            CONSTRAINT chk_experience_dates CHECK (
                                finish_date IS NULL OR start_date <= finish_date
                                ),
                            CONSTRAINT chk_experience_current CHECK (
                                NOT (work_current = TRUE AND finish_date IS NOT NULL)
                                )
);

CREATE TABLE certification (
                               certification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               name VARCHAR(150),
                               finish_date DATE,
                               in_progress BOOLEAN DEFAULT FALSE,
                               certificate BYTEA,
                               user_id BIGINT NOT NULL,
                               institution_id BIGINT NOT NULL,
                               CONSTRAINT fk_certification_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                                   ON DELETE CASCADE ON UPDATE CASCADE,
                               CONSTRAINT fk_certification_institution FOREIGN KEY (institution_id) REFERENCES institution(institution_id)
                                   ON DELETE RESTRICT ON UPDATE CASCADE,
                               CONSTRAINT chk_certification_in_progress CHECK (
                                   NOT (in_progress = TRUE AND finish_date IS NOT NULL)
                                   )
);

CREATE TABLE project (
                         project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         title VARCHAR(150) NOT NULL,
                         description TEXT NOT NULL,
                         link VARCHAR(255) NOT NULL,
                         user_id BIGINT NOT NULL,
                         CONSTRAINT fk_project_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                             ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE user_language (
                               user_language_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               user_id BIGINT NOT NULL,
                               language_id BIGINT NOT NULL,
                               level VARCHAR(50) NOT NULL,
                               CONSTRAINT uq_user_language UNIQUE (user_id, language_id),
                               CONSTRAINT fk_user_language_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                                   ON DELETE CASCADE ON UPDATE CASCADE,
                               CONSTRAINT fk_user_language_language FOREIGN KEY (language_id) REFERENCES language(language_id)
                                   ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE user_role (
                           user_id BIGINT NOT NULL,
                           role_id BIGINT NOT NULL,
                           CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
                           CONSTRAINT fk_user_role_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                               ON DELETE CASCADE ON UPDATE CASCADE,
                           CONSTRAINT fk_user_role_role FOREIGN KEY (role_id) REFERENCES role(role_id)
                               ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE user_ability (
                              user_id BIGINT NOT NULL,
                              ability_id BIGINT NOT NULL,
                              CONSTRAINT pk_user_ability PRIMARY KEY (user_id, ability_id),
                              CONSTRAINT fk_user_ability_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                                  ON DELETE CASCADE ON UPDATE CASCADE,
                              CONSTRAINT fk_user_ability_ability FOREIGN KEY (ability_id) REFERENCES ability(ability_id)
                                  ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE user_social_network (
                                     user_social_network_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     user_id BIGINT NOT NULL,
                                     social_network_id BIGINT NOT NULL,
                                     link VARCHAR(255),
                                     CONSTRAINT uq_user_social_network UNIQUE (user_id, social_network_id),
                                     CONSTRAINT fk_user_social_network_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                                         ON DELETE CASCADE ON UPDATE CASCADE,
                                     CONSTRAINT fk_user_social_network_network FOREIGN KEY (social_network_id) REFERENCES social_network(social_network_id)
                                         ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE user_curriculum (
                                 user_curriculum_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 title VARCHAR(255) NOT NULL,
                                 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 curriculum OID NOT NULL,
                                 user_id BIGINT NOT NULL,
                                 CONSTRAINT fk_user_curriculum_user FOREIGN KEY (user_id) REFERENCES users(user_id)
                                     ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE project_ability (
                                 project_id BIGINT NOT NULL,
                                 ability_id BIGINT NOT NULL,
                                 CONSTRAINT pk_project_ability PRIMARY KEY (project_id, ability_id),
                                 CONSTRAINT fk_project_ability_project FOREIGN KEY (project_id) REFERENCES project(project_id)
                                     ON DELETE CASCADE ON UPDATE CASCADE,
                                 CONSTRAINT fk_project_ability_ability FOREIGN KEY (ability_id) REFERENCES ability(ability_id)
                                     ON DELETE CASCADE ON UPDATE CASCADE
);